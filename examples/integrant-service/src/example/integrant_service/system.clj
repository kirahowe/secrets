(ns example.integrant-service.system
  "Integrant lifecycle methods for the small example service.

  The secrets component returns an ordinary map.  The HTTP component only
  derives a count and configured flag from that map; it never serializes the
  map or logs its values."
  (:require [clojure.java.io :as io]
            [com.kirahowe.secrets :as secrets]
            [integrant.core :as ig])
  (:import (com.sun.net.httpserver HttpExchange HttpHandler HttpServer)
           (java.net InetSocketAddress)
           (java.nio.charset StandardCharsets)))

(def secrets-key :example.integrant-service/secrets)
(def http-key :example.integrant-service/http)

(defn- source-for [{:keys [resource file]}]
  (or file (when resource (io/resource resource))))

(defmethod ig/init-key secrets-key
  [_ {:keys [app identity-file] :as opts}]
  ;; `load-secrets` accepts a classpath URL, which also works when this example
  ;; is packaged as an uberjar.  The identity is resolved from the documented
  ;; environment variables unless an explicit path is supplied.
  (let [identity-or-options (cond-> {}
                              app (assoc :app app)
                              identity-file (assoc :identity-file identity-file))]
    (secrets/load-secrets (source-for opts) identity-or-options)))

(defmethod ig/halt-key! secrets-key [_ _]
  nil)

(defn safe-status
  "Return status data safe to expose over the health endpoint.

  The positional `secret-map` argument is the resolved secrets component value.
  This intentionally contains no secret keys or values."
  [secret-map]
  {:status "ok"
   :secrets-configured (map? secret-map)
   :secret-count (if (map? secret-map) (count secret-map) 0)})

(defn- status-json [{:keys [status secrets-configured secret-count]}]
  ;; The values are generated by this namespace and are not sourced from the
  ;; secret map, so a JSON dependency would add no value for this demo.
  (format "{\"status\":\"%s\",\"secretsConfigured\":%s,\"secretCount\":%d}"
          status secrets-configured secret-count))

(defn- respond! [^HttpExchange exchange body]
  (let [bytes (.getBytes body StandardCharsets/UTF_8)]
    (.set (.getResponseHeaders exchange) "Content-Type" "application/json")
    (.sendResponseHeaders exchange 200 (long (alength bytes)))
    (with-open [out (.getResponseBody exchange)]
      (.write out bytes))))

(defmethod ig/init-key http-key
  [_ {:keys [port secrets]}]
  (let [server (HttpServer/create (InetSocketAddress. (int (or port 8080))) 0)
        status (safe-status secrets)]
    (.createContext server "/health"
                    (reify HttpHandler
                      (handle [_ exchange]
                        (respond! exchange (status-json status)))))
    (.setExecutor server nil)
    (.start server)
    {:server server
     :port (.getPort (.getAddress server))
     :status status}))

(defmethod ig/halt-key! http-key
  [_ {:keys [^HttpServer server]}]
  (when server (.stop server 0)))
